const { _electron } = require('playwright')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')

const project = path.resolve(__dirname, '..')
const commandKey = process.platform === 'darwin' ? 'Meta' : 'Control'

async function run() {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'margin-desktop-'))
  const profile = path.join(root, 'profile'), folder = path.join(root, 'notes')
  await fs.mkdir(profile)
  await fs.mkdir(path.join(folder, 'chapters'), { recursive: true })
  const start = '# Start\n\nRead deeply with **important text** and useful ideas. #guide\n\n[[chapters/One#Details|Visit One]] · [[Missing]]\n\n![[chapters/One#Details]]\n\n![Small image](pixel.png)\n\n## Next chapter\n\n' + Array.from({ length: 40 }, (_, i) => `Paragraph ${i + 1}. This document remembers your reading place.\n`).join('\n')
  await fs.writeFile(path.join(folder, 'Start.md'), start)
  await fs.writeFile(path.join(folder, 'chapters/One.md'), '---\naliases:\n  - First note\ntags:\n  - guide\n  - work/project\n---\n# One\n\nA **bold** thought.\n\n## Details\n\nEmbedded details and [[../Start]]. A [reference][manual] with footnote[^one]. #guide\n\n$$\\frac{a}{b} + x^2$$\n\n```mermaid\nflowchart LR\nDraft --> Read\n```\n\n## After\n\nNot embedded.\n\n[manual]: https://example.test/manual\n\n[^one]: A **useful** footnote.')
  await fs.writeFile(path.join(folder, 'Two.md'), '# Two\n\n[[Start]] and [[chapters/One]].')
  await fs.writeFile(path.join(folder, 'pixel.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jZ1kAAAAASUVORK5CYII=', 'base64'))
  const errors = [], network = []
  const launch = () => _electron.launch({
    executablePath: process.env.MARGIN_SMOKE_EXECUTABLE || require('electron'),
    args: [...(process.env.MARGIN_SMOKE_EXECUTABLE ? [] : [project]), `--user-data-dir=${profile}`, ...(process.platform === 'linux' && process.env.MARGIN_TEST_NO_SANDBOX === '1' ? ['--no-sandbox'] : [])],
    cwd: project, env: { ...process.env, NODE_ENV: 'test', MARGIN_TEST_USER_DATA: profile },
  })
  let app = await launch()
  const observe = async () => {
    const page = await app.firstWindow()
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('request', (request) => { if (/^https?:/.test(request.url())) network.push(request.url()) })
    page.setDefaultTimeout(15_000)
    return page
  }
  const send = (command) => app.evaluate(({ BrowserWindow }, value) => BrowserWindow.getAllWindows()[0].webContents.send('app-command', value), command)
  const capture = (page, name) => page.screenshot({ path: path.join(root, `${name}.png`) })
  try {
    assert.equal(await fs.realpath(await app.evaluate(({ app }) => app.getPath('userData'))), await fs.realpath(profile))
    const blocked = await app.evaluate(({ net }) => new Promise((resolve) => {
      const request = net.request('https://example.test/margin-offline-check')
      request.on('response', () => resolve('unexpected response'))
      request.on('error', (error) => resolve(error.message))
      request.end()
    }))
    assert.match(String(blocked), /ERR_BLOCKED_BY_CLIENT/)
    await app.evaluate(({ dialog }, paths) => {
      dialog.showOpenDialog = async (_parent, options) => ({ canceled: false, filePaths: [options.properties.includes('openDirectory') ? paths.folder : paths.start] })
      dialog.showSaveDialog = async (_parent, options) => ({ canceled: false, filePath: `${paths.folder}/export.${options.filters?.[0]?.extensions?.includes('pdf') ? 'pdf' : 'html'}` })
      dialog.showMessageBox = async (_parent, options) => ({ response: Math.max(0, options.buttons.findIndex((label) => /discard|don.t save/i.test(label))) })
    }, { folder, start: path.join(folder, 'Start.md') })
    const page = await observe()
    await page.getByRole('button', { name: 'Open folder', exact: true }).click()
    await page.getByRole('button', { name: 'Open file', exact: true }).click()
    await page.locator('.note-embed-body .footnotes strong').waitFor()
    await page.locator('.note-embed-body .mermaid-block.is-rendered svg').waitFor()
    assert.equal(await page.locator('.note-embed-body .katex').count(), 1)
    assert.match(await page.locator('.note-embed-body').innerText(), /Embedded details/)
    assert.doesNotMatch(await page.locator('.note-embed-body').innerText(), /Not embedded/)
    assert.equal(await page.locator('.note-embed-body a[href="https://example.test/manual"]').count(), 1)
    await page.getByRole('button', { name: 'Reading tools and connections', exact: true }).click()
    await page.getByRole('button', { name: 'Bookmark document', exact: true }).click()
    await page.evaluate(() => {
      const text = [...document.querySelector('.preview-pane article > p').childNodes].find((node) => node.nodeType === Node.TEXT_NODE)
      const range = document.createRange()
      range.setStart(text, 0); range.setEnd(text, 11)
      const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
      document.querySelector('.preview-pane article').dispatchEvent(new MouseEvent('mouseup', { bubbles: true }))
    })
    await page.getByRole('button', { name: 'Highlight', exact: true }).click()
    await page.getByRole('textbox', { name: 'Annotation note', exact: true }).fill('A local reading note.')
    assert.equal(await page.locator('mark[data-margin-annotation]').count(), 1)
    // Real Chromium selections insert paragraph separators, unlike jsdom's Range strings.
    await page.locator('.preview-pane article > p').filter({ hasText: /^Paragraph 1\./ }).scrollIntoViewIfNeeded()
    await page.evaluate(() => {
      const paragraphs = [...document.querySelectorAll('.preview-pane article > p')].filter((p) => p.textContent.startsWith('Paragraph'))
      const range = document.createRange()
      range.setStart(paragraphs[0].firstChild, 0); range.setEnd(paragraphs[1].firstChild, 11)
      const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range)
      document.querySelector('.preview-pane article').dispatchEvent(new MouseEvent('mouseup', { bubbles: true }))
    })
    await page.getByRole('button', { name: 'Highlight', exact: true }).click()
    assert.equal(await page.locator('.annotation-card').count(), 2)
    assert.equal(await fs.readFile(path.join(folder, 'Start.md'), 'utf8'), start)
    await send('exportHtml')
    await page.getByText('HTML exported', { exact: true }).waitFor()
    const exported = await fs.readFile(path.join(folder, 'export.html'), 'utf8')
    assert.match(exported, /Embedded details/); assert.match(exported, /data:image\/png;base64/)
    await send('exportPdf')
    await page.getByText('PDF exported', { exact: true }).waitFor({ timeout: 30_000 })
    assert.equal((await fs.readFile(path.join(folder, 'export.pdf'))).subarray(0, 5).toString(), '%PDF-')
    await page.locator('[data-margin-fold="next-chapter"]').click({ force: true })
    assert.equal(await page.locator('.preview-pane article > p').last().isVisible(), false)
    await page.locator('[data-margin-fold="next-chapter"]').click({ force: true })
    await page.locator('.preview-pane img').click()
    await page.getByRole('button', { name: 'Zoom image in', exact: true }).click()
    assert.match(await page.locator('.image-modal header').innerText(), /125%/)
    await page.getByRole('button', { name: 'Close image viewer', exact: true }).click()
    await page.getByRole('button', { name: 'Present document', exact: true }).click()
    await page.getByRole('button', { name: 'Next slide', exact: true }).click()
    assert.match(await page.locator('.presentation-modal footer').innerText(), /2 \/ 2/)
    await page.getByRole('button', { name: 'Close presentation', exact: true }).click()
    await page.getByRole('link', { name: 'Visit One', exact: true }).click()
    await page.locator('.tab-select[aria-selected="true"]').filter({ hasText: 'One.md' }).waitFor()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await page.locator('.tab-select[aria-selected="true"]').filter({ hasText: 'Start.md' }).waitFor()
    await page.getByRole('button', { name: 'Forward', exact: true }).click()
    await page.locator('.tab-select[aria-selected="true"]').filter({ hasText: 'One.md' }).waitFor()
    await page.getByRole('tab', { name: 'Links', exact: true }).click()
    assert.match(await page.locator('.reading-tools-scroll').innerText(), /Backlinks/i)
    await page.getByRole('tab', { name: 'Tags', exact: true }).click()
    await page.getByRole('button', { name: /^#work\/project/ }).click()
    assert.equal(await page.locator('.reading-tools .desk-note-link').filter({ hasText: 'chapters/One.md' }).count(), 1)
    await page.getByRole('tab', { name: 'Links', exact: true }).click()
    await page.getByRole('button', { name: 'Live edit', exact: true }).click()
    await page.locator('.live-editor.is-active .cm-live-block a[href="https://example.test/manual"]').waitFor()
    await capture(page, 'live')
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('button', { name: 'Paragraph', exact: true }).click()
    await page.getByRole('button', { name: 'Close settings', exact: true }).click()
    assert.equal(await page.locator('.live-editor.is-active .cm-live-block').first().evaluate((block) => getComputedStyle(block).opacity), '0.32')
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('button', { name: 'Off', exact: true }).click()
    await page.getByRole('button', { name: 'Close settings', exact: true }).click()
    await page.locator('.live-editor.is-active .cm-live-block strong').first().click()
    await page.keyboard.press('End'); await page.keyboard.type(' Added text.')
    await page.getByRole('button', { name: 'Edit', exact: true }).click()
    assert.match(await page.locator('.editor-pane.is-active .cm-content').innerText(), /Added text\./)
    await page.locator('.editor-pane.is-active .cm-content').click(); await page.keyboard.press(`${commandKey}+z`)
    await page.getByRole('button', { name: 'Read', exact: true }).click()
    await page.locator('.preview-pane a[data-margin-note="../Start"]').first().click()
    await page.locator('.preview-pane a[data-margin-note="Missing"]').click()
    await page.getByRole('button', { name: 'Create note', exact: true }).click()
    await page.locator('.tab-select[aria-selected="true"]').filter({ hasText: 'Missing.md' }).waitFor()
    assert.equal(await fs.readFile(path.join(folder, 'Missing.md'), 'utf8'), '')
    await page.locator('.editor-pane.is-active .cm-content').click(); await page.keyboard.type('[[Sta')
    await page.getByRole('option').filter({ hasText: 'Start.md' }).click()
    await page.getByRole('button', { name: 'Edit', exact: true }).click()
    assert.match(await page.locator('.editor-pane.is-active .cm-content').innerText(), /\[\[Start\]\]/)
    await page.getByRole('button', { name: 'Note graph', exact: true }).click()
    await page.locator('.graph-node').first().waitFor()
    assert.equal(await page.locator('.graph-node').count(), 4)
    await capture(page, 'graph')
    await page.getByRole('textbox', { name: 'Filter graph', exact: true }).fill('Two')
    assert.equal(await page.locator('.graph-node').count(), 1)
    await page.getByRole('button', { name: 'Zoom graph in', exact: true }).click()
    await page.getByRole('button', { name: 'Open Two', exact: true }).click()
    await page.locator('.tab-select[aria-selected="true"]').filter({ hasText: 'Two.md' }).waitFor()
    await page.getByRole('tab', { name: 'Start.md', exact: true }).click()
    await page.getByRole('button', { name: 'Read', exact: true }).click()
    await page.getByRole('tab', { name: 'Reading', exact: true }).click()
    await page.waitForFunction(() => localStorage.getItem('margin:reading-library:v1')?.includes('A local reading note.'))
    await page.reload()
    await page.getByRole('button', { name: 'Open file', exact: true }).click()
    await page.getByRole('button', { name: 'Reading tools and connections', exact: true }).click()
    await page.getByRole('textbox', { name: 'Annotation note', exact: true }).first().waitFor()
    assert.equal(await page.getByRole('textbox', { name: 'Annotation note', exact: true }).first().inputValue(), 'A local reading note.')
    await capture(page, 'reading')
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('button', { name: 'Dark', exact: true }).click()
    await page.getByRole('button', { name: 'Midnight', exact: true }).click()
    await page.getByRole('button', { name: 'Close settings', exact: true }).click()
    const nativeWindow = await app.browserWindow(page)
    await nativeWindow.evaluate((window) => window.setContentSize(880, 700))
    await capture(page, 'dark-small')
    assert.equal(await page.locator('.preview-pane').evaluate((pane) => getComputedStyle(pane).backgroundColor), 'rgb(25, 28, 27)')
    await nativeWindow.evaluate((window) => window.setContentSize(1280, 820))
    // Close in the same task that scrolls, before a debounce or repaint can save it.
    await page.evaluate(() => {
      const pane = document.querySelector('.preview-pane'); pane.scrollTop = 1200
      pane.dispatchEvent(new Event('scroll', { bubbles: false }))
      document.querySelector('button[aria-label="Close Start.md"]').click()
    })
    await page.locator('.reading-tools .desk-note-link').filter({ hasText: 'Start.md' }).click()
    await page.waitForFunction(() => document.querySelector('.preview-pane')?.scrollTop > 1100)
    await page.evaluate(() => {
      const original = Storage.prototype.setItem
      window.marginRestoreStorageForTest = () => { Storage.prototype.setItem = original }
      Storage.prototype.setItem = function (key, value) {
        if (key === 'margin:reading-library:v1') throw new DOMException('Test storage failure', 'QuotaExceededError')
        return original.call(this, key, value)
      }
    })
    await send('requestWindowClose')
    await page.getByText('Reading notes could not be saved. Free local storage or remove older annotations before quitting.', { exact: true }).waitFor()
    assert.equal(page.isClosed(), false)
    await page.evaluate(() => window.marginRestoreStorageForTest())
    const closed = app.waitForEvent('close', { timeout: 15_000 })
    await app.evaluate(({ app }) => app.quit()).catch(() => {})
    await closed
    app = await launch()
    const restarted = await observe()
    await restarted.getByRole('button', { name: 'Reading tools and connections', exact: true }).click()
    await restarted.locator('.reading-tools .desk-note-link').filter({ hasText: 'Start.md' }).click()
    await restarted.getByRole('textbox', { name: 'Annotation note', exact: true }).first().waitFor()
    assert.equal(await restarted.getByRole('textbox', { name: 'Annotation note', exact: true }).first().inputValue(), 'A local reading note.')
    await restarted.waitForFunction(() => document.querySelector('.preview-pane')?.scrollTop > 1100)
    assert.deepEqual(errors, []); assert.deepEqual(network, [])
    console.log(JSON.stringify({ status: 'passed', platform: process.platform, artifacts: root, checks: ['native file/folder opening', 'linked notes and contextual embeds', 'cross-paragraph annotations without source changes', 'HTML/PDF export', 'folds', 'image viewer', 'slides', 'history', 'live editing/undo', 'note creation/completion', 'graph', 'dark/narrow layouts', 'immediate-close reading position', 'restart persistence', 'no HTTP requests'] }, null, 2))
  } catch (error) {
    const page = await app.firstWindow().catch(() => null)
    if (page) await capture(page, 'failure').catch(() => {})
    console.error(`Smoke artifacts: ${root}`)
    throw error
  } finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}) }
}
run().catch((error) => { console.error(error); process.exitCode = 1 })
